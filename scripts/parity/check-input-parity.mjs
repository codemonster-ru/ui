#!/usr/bin/env node
// Three-way parity gate for a component's shared cases.
//
// The component is chosen with `--component=<id>`; it defaults to VfInput, the
// component this gate was built for in M07. Everything below is component-blind
// and reads the profile.
//
//   reference Vue -> current Vue    the Vue contract is preserved
//   reference Vue -> Razor          the historical product reaches the new adapter
//   current Vue  -> Razor           the two adapters have not diverged
//
// The first direction is what stops the last one from passing while both new
// implementations are wrong together.
//
// The gate fails on three separate things, in this order:
//   1. a malformed divergence registry, before a browser is even launched;
//   2. any difference the registry does not name;
//   3. a registry rule that matched nothing, or matched more than it says.
// The third is what makes "224 approved divergences" stop being a number
// nobody can check.
import { writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { repositoryRoot, stableStringify } from '../baseline/reference.mjs';
import { directions } from './compare.mjs';
import { profileFromArgv } from './profiles.mjs';
import {
  assertPolicyIsWellFormed,
  captureAll,
  collectPageErrors,
  compareCaptures,
  loadCatalog,
  loadParityPolicy,
  runDirectoryFor,
  themes,
  viewport,
} from './run.mjs';

const profile = profileFromArgv();
const runDirectory = runDirectoryFor(profile);
const catalog = loadCatalog(profile);
const policy = loadParityPolicy(profile);

assertPolicyIsWellFormed(policy, catalog);
process.stdout.write(`Divergence policy is well formed: ${policy.approvedDivergences.length} approval(s).\n`);

const { targets, captures, browser } = await captureAll(catalog, { log: (line) => process.stdout.write(line) });
const result = compareCaptures(captures, catalog, policy);
const pageErrors = collectPageErrors(captures);

const report = {
  $comment: `Three-way ${profile.label} parity report. Generated by scripts/parity/check-input-parity.mjs.`,
  generatedFor: { cases: catalog.cases.length, themes, viewport, directions: directions.map((d) => d.id) },
  provenance: Object.fromEntries(Object.entries(targets).map(([label, target]) => [label, target.provenance])),
  environment: {
    deviceScaleFactor: 1,
    locale: 'en-US',
    timezone: 'UTC',
    reducedMotion: 'reduce',
    browser,
  },
  summary: result.summary,
  approvalUsage: result.approvalUsage,
  interactionEvidence: Object.fromEntries(
    Object.entries(captures).map(([target, byTheme]) => [
      target,
      Object.fromEntries(
        Object.entries(byTheme).map(([theme, capture]) => [
          theme,
          Object.fromEntries(
            Object.entries(capture.interactions).map(([caseId, interaction]) => [
              caseId,
              {
                // The whole snapshot, not a hand-listed subset. The subset was
                // VfInput's fields, so VfIconButton's activation count and
                // pressed state were missing from the evidence of the run that
                // checked them. `clip` is dropped because it is where the
                // screenshot was taken, and the screenshot itself is recorded.
                ...Object.fromEntries(Object.entries(interaction).filter(([field]) => field !== 'clip')),
                postInteractionScreenshot: capture.interactionScreenshots[caseId],
                naturalPostInteractionScreenshot: capture.naturalInteractionScreenshots[caseId],
              },
            ]),
          ),
        ]),
      ),
    ]),
  ),
  failures: result.failures,
  approvedDivergences: result.approved,
  pageErrors,
};

const reportPath = resolve(runDirectory, profile.reportName);
writeFileSync(reportPath, stableStringify(report));

process.stdout.write(
  `\n${catalog.cases.length} cases x ${themes.length} themes x ${directions.length} directions ` +
    `= ${result.summary.caseComparisons} case comparisons, ` +
    `${result.summary.visualComparisons} initial screenshot comparisons, ` +
    `${result.summary.postInteractionVisualComparisons} post-interaction screenshot comparisons.\n` +
    `Report: ${relative(repositoryRoot, reportPath)}\n`,
);

process.stdout.write('\nApproved divergences, by rule:\n');
for (const row of result.approvalUsage) {
  process.stdout.write(
    `  ${row.occurrences.toString().padStart(3)}/${row.expectedOccurrences} ${row.id} ` +
      `[${row.dimension}${row.detail ? `/${row.detail}` : ''} -> ${row.target}]\n` +
      `      ${row.caseIds.length} case(s): ${row.caseIds.join(', ')}\n`,
  );
}

if (pageErrors.length > 0) {
  process.stderr.write(`\nPage errors:\n  - ${pageErrors.join('\n  - ')}\n`);
}

if (result.approvalProblems.length > 0) {
  process.stderr.write(
    `\n[${profile.id}-parity] divergence registry problems:\n  - ${result.approvalProblems.join('\n  - ')}\n`,
  );
}

if (result.failures.length > 0) {
  process.stderr.write(`\n[${profile.id}-parity] FAILED with ${result.failures.length} unapproved difference(s):\n`);
  for (const failure of result.failures.slice(0, 40)) {
    process.stderr.write(
      `  - ${failure.caseId} [${failure.direction}/${failure.theme}] ${failure.dimension} (${failure.classification})` +
        ` at ${failure.path}${failure.detail ? ` ${failure.detail}` : ''}\n` +
        `      ${failure.direction.split('-vs-')[0]}: ${JSON.stringify(failure.left)}\n` +
        `      ${failure.direction.split('-vs-')[1]}: ${JSON.stringify(failure.right)}\n`,
    );
  }
  if (result.failures.length > 40) {
    process.stderr.write(`  ... ${result.failures.length - 40} more in the report.\n`);
  }
}

if (result.failures.length > 0 || pageErrors.length > 0 || result.approvalProblems.length > 0) {
  process.exit(1);
}

process.stdout.write(`\n[${profile.id}-parity] OK: three-way parity holds for every shared ${profile.label} case.\n`);
