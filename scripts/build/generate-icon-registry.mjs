// Generates the neutral icon registry, from the Vue icon system.
//
// The Vue icons package stays the single geometry owner. This script
// server-renders every glyph it publishes and writes their shape as plain data,
// so any adapter can draw the same icons without importing a Vue component.
// Nothing here is hand-transcribed: re-running it is the only supported way to
// change the artifact, and `npm run check:icon-data` fails when a committed copy
// drifts from a fresh render.
//
// M10 replaced a per-component extraction with this registry. VfInput used to
// have its own three-glyph blob; a second component would have wanted its own,
// and a tenth would have wanted a tenth. One registry covering the published
// icon set means migrating a component needs no icon work at all.
//
// Layout is no longer carried here. The declarations the glyph needs now live in
// packages/styles/src/components/icon.css, which both adapters load, so the
// registry carries only what is genuinely per-icon data: the optical offset
// custom properties the component computes and the glyph body itself.
//
// Run through vite-node so the real SFC is compiled:
//   npm run icons:registry
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createSSRApp, h } from 'vue';
import { renderToString } from '@vue/server-renderer';
import { iconNames, VueIconify } from '../../packages/icons/src/lib/index.ts';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

// Every published glyph, in the kebab-case spelling `icons.<name>` resolves to.
// Derived, never listed: a new icon in the Vue package appears here by itself.
const toKebabCase = (value) => value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

export const registryIconNames = [...iconNames].map(toKebabCase).sort();

const SIZE_PLACEHOLDER = '__VF_ICON_SIZE__';

function parseRenderedIcon(name, html) {
  const wrapper = html.match(/^<span class="([^"]*)" style="([^"]*)">(.*)<\/span>$/s);
  if (!wrapper) {
    throw new Error(`Unexpected wrapper markup for icon "${name}".`);
  }

  const [, wrapperClass, wrapperStyle, svgMarkup] = wrapper;
  const svg = svgMarkup.match(/^<svg ([^>]*)>(.*)<\/svg>$/s);
  if (!svg) {
    throw new Error(`Unexpected svg markup for icon "${name}".`);
  }

  const [, attributeSource, body] = svg;
  const attributes = {};
  for (const [, attributeName, value] of attributeSource.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) {
    attributes[attributeName] = value;
  }

  if (attributes.width !== SIZE_PLACEHOLDER || attributes.height !== SIZE_PLACEHOLDER) {
    throw new Error(`Icon "${name}" did not render the size placeholder; the icon API may have changed.`);
  }

  delete attributes.width;
  delete attributes.height;

  // Self-closing form keeps the data usable by a plain string renderer.
  const normalisedBody = body.replace(/><\/(path|circle|line|rect|polyline|polygon|ellipse)>/g, '/>');

  return { wrapperClass, wrapperStyle, attributes, body: normalisedBody };
}

async function renderIcon(name) {
  const app = createSSRApp({ render: () => h(VueIconify, { icon: name, size: SIZE_PLACEHOLDER }) });
  app.config.warnHandler = () => {};

  return parseRenderedIcon(name, await renderToString(app));
}

export async function buildIconRegistry() {
  const icons = {};

  for (const name of registryIconNames) {
    icons[name] = await renderIcon(name);
  }

  return {
    $comment:
      'Neutral icon registry. Generated from packages/icons by scripts/build/generate-icon-registry.mjs. ' +
      'Do not edit by hand; run npm run icons:registry -- --write. Layout lives in ' +
      'packages/styles/src/components/icon.css, which every adapter loads.',
    icons,
  };
}

export const iconRegistryTargets = [
  // The canonical neutral copy every adapter reads from in the repository.
  'packages/shared-core/src/icons/icon-registry.json',
  // The distribution copy the Composer artifact ships, generated by the same run.
  'packages/razor/resources/icons/icon-registry.json',
];

export function serialiseIconRegistry(data) {
  return `${JSON.stringify(data, null, 2)}\n`;
}

// `--write` regenerates the artifacts; the default mode compares the committed
// copies against a fresh render and fails on drift, so neither the canonical
// file nor the packaged Razor copy can be edited by hand.
const shouldWrite = process.argv.includes('--write');
const serialised = serialiseIconRegistry(await buildIconRegistry());
const differences = [];

for (const target of iconRegistryTargets) {
  const absolutePath = resolve(repositoryRoot, target);

  if (shouldWrite) {
    mkdirSync(dirname(absolutePath), { recursive: true });
    writeFileSync(absolutePath, serialised);
    process.stdout.write(`Wrote ${target}\n`);
    continue;
  }

  if (!existsSync(absolutePath)) {
    differences.push(`${target}: missing; run npm run icons:registry -- --write`);
    continue;
  }

  if (readFileSync(absolutePath, 'utf8') !== serialised) {
    differences.push(`${target}: differs from a fresh render of the Vue icon system`);
  }
}

if (differences.length > 0) {
  process.stderr.write(`Icon registry drifted:\n  - ${differences.join('\n  - ')}\n`);
  process.exit(1);
}

if (!shouldWrite) {
  process.stdout.write(
    `Icon registry matches the Vue icon system: ${registryIconNames.length} glyphs, ` +
      `${iconRegistryTargets.length} artifacts in sync.\n`,
  );
}
