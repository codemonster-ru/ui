#!/usr/bin/env node
// Builds the assets a PHP host serves for the Razor adapter.
//
// Two artifacts land in packages/razor/dist:
//
//   vueforge-razor.css  the canonical stylesheet, composed from the sources
//                       that already own those rules. This package authors no
//                       CSS: every rule is inlined from packages/styles (the
//                       Input closure), the generated theme tokens and the core
//                       foundation. A provenance manifest records the exact
//                       sources and their hashes.
//   vueforge-razor.js   the browser controller, bundled with the shared rules
//                       it imports. shared-core is private and unpublished, so
//                       it is inlined rather than left as an import.
//
// Copying built artifacts is how a Composer package stays self-contained; it is
// not a source dependency on the Vue adapter.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(packageRoot, '../..');
const distDirectory = resolve(packageRoot, 'dist');

// Ordered exactly as a page needs them: tokens, then the theme layer, then the
// foundation, then the component closure.
const styleSources = [
  'packages/core/.generated/theme/tokens.css',
  'packages/core/.generated/theme/theme.css',
  'packages/core/src/styles/components/base.css',
  'packages/styles/src/components/input.css',
];

function inlineCssImports(filePath, seen = new Set()) {
  if (seen.has(filePath)) {
    return '';
  }

  seen.add(filePath);

  return readFileSync(filePath, 'utf8').replace(/^@import\s+['"](.+?)['"];\s*$/gm, (statement, importPath) =>
    importPath.startsWith('.') ? inlineCssImports(resolve(dirname(filePath), importPath), seen) : statement,
  );
}

function buildStylesheet() {
  const seen = new Set();
  const provenance = [];
  const parts = [];

  for (const source of styleSources) {
    const absolutePath = resolve(repositoryRoot, source);

    if (!existsSync(absolutePath)) {
      throw new Error(
        `Missing canonical stylesheet source: ${source}. Run the core package build first so the generated theme CSS exists.`,
      );
    }

    provenance.push({ source, sha256: createHash('sha256').update(readFileSync(absolutePath)).digest('hex') });
    const inlined = inlineCssImports(absolutePath, seen);
    if (inlined.trim() !== '') {
      parts.push(inlined);
    }
  }

  return { css: parts.join('\n'), provenance };
}

mkdirSync(distDirectory, { recursive: true });

const { css, provenance } = buildStylesheet();
const banner = '/* Generated by packages/razor/build-assets.mjs. Canonical rules live in packages/styles. */\n';
writeFileSync(resolve(distDirectory, 'vueforge-razor.css'), banner + css);

execFileSync(
  resolve(repositoryRoot, 'node_modules/.bin/esbuild'),
  [
    resolve(packageRoot, 'browser/input.ts'),
    '--bundle',
    '--format=esm',
    '--target=es2022',
    `--alias:@codemonster-ru/vueforge-shared-core=${resolve(repositoryRoot, 'packages/shared-core/src/index.ts')}`,
    `--outfile=${resolve(distDirectory, 'vueforge-razor.js')}`,
  ],
  { stdio: ['ignore', 'ignore', 'pipe'] },
);

const manifest = {
  $comment: 'Generated by packages/razor/build-assets.mjs. Records where every packaged rule came from.',
  styles: provenance,
  artifacts: Object.fromEntries(
    ['vueforge-razor.css', 'vueforge-razor.js'].map((name) => [
      name,
      createHash('sha256').update(readFileSync(resolve(distDirectory, name))).digest('hex'),
    ]),
  ),
};
writeFileSync(resolve(distDirectory, 'assets-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

process.stdout.write(
  `Built Razor assets in ${relative(repositoryRoot, distDirectory)}: ` +
    `${provenance.length} canonical stylesheet sources, 2 artifacts.\n`,
);
