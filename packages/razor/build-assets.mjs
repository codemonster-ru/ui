#!/usr/bin/env node
// Builds the assets a PHP host serves for the Razor adapter.
//
// Two artifacts land in packages/razor/dist:
//
//   vueforge-razor.css  the canonical stylesheet, composed from the sources
//                       that already own those rules. This package authors no
//                       CSS: every rule is inlined from packages/styles (the
//                       Input closure), the generated theme tokens and the core
//                       foundation. A provenance manifest records the exact
//                       sources and their hashes.
//   vueforge-razor.js   the browser controller, bundled with the shared rules
//                       it imports. shared-core is private and unpublished, so
//                       it is inlined rather than left as an import. Since M28
//                       it also bundles @codemonster-ru/floater.js, exactly
//                       1.0.11, which the dropdown positions its menu with -
//                       see FLOATER below.
//
// Copying built artifacts is how a Composer package stays self-contained; it is
// not a source dependency on the Vue adapter.
import { styleSources } from './style-sources.mjs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(packageRoot, '../..');
// `--out-dir` lets the release stage build straight into the artifact it is
// assembling, so a stale packages/razor/dist from an earlier run can never be
// what a consumer receives.
const outDirArgument = process.argv.find((argument) => argument.startsWith('--out-dir='));
const distDirectory = outDirArgument
  ? resolve(process.cwd(), outDirArgument.slice('--out-dir='.length))
  : resolve(packageRoot, 'dist');

// Ordered exactly as a page needs them: tokens, then the theme layer, then the
// foundation, then the component closure.
//
// Every entry is owned by a neutral package. Before M09 the first three came
// from packages/core, which meant the Razor adapter could not build without the
// Vue adapter. scripts/ci/check-asset-boundary.mjs fails if a path outside
// theme, styles or shared-core reappears here.

function inlineCssImports(filePath, seen = new Set()) {
  if (seen.has(filePath)) {
    return '';
  }

  seen.add(filePath);

  return readFileSync(filePath, 'utf8').replace(/^@import\s+['"](.+?)['"];\s*$/gm, (statement, importPath) =>
    importPath.startsWith('.') ? inlineCssImports(resolve(dirname(filePath), importPath), seen) : statement,
  );
}

function buildStylesheet() {
  const seen = new Set();
  const provenance = [];
  const parts = [];

  for (const source of styleSources) {
    const absolutePath = resolve(repositoryRoot, source);

    if (!existsSync(absolutePath)) {
      throw new Error(
        `Missing canonical stylesheet source: ${source}. ` +
          'Run `npm run theme:tokens` first so the generated token CSS exists.',
      );
    }

    provenance.push({ source, sha256: createHash('sha256').update(readFileSync(absolutePath)).digest('hex') });
    const inlined = inlineCssImports(absolutePath, seen);
    if (inlined.trim() !== '') {
      parts.push(inlined);
    }
  }

  return { css: parts.join('\n'), provenance };
}

mkdirSync(distDirectory, { recursive: true });

const { css, provenance } = buildStylesheet();
const banner = '/* Generated by packages/razor/build-assets.mjs. Canonical rules live in packages/styles. */\n';
writeFileSync(resolve(distDirectory, 'vueforge-razor.css'), banner + css);

// The one third-party runtime dependency of the browser artifact. Pinned to an
// exact version in the root package.json, checked here against what is
// installed, and bundled - never fetched: a Composer consumer runs no Node,
// npm or Vite, so whatever the controller needs has to be inside this file.
// The package is MIT and its dist carries no @license comment for esbuild to
// keep, so the notice the licence requires in copies is written as the
// artifact's banner, verbatim from the installed package.
const FLOATER = { name: '@codemonster-ru/floater.js', version: '1.0.11' };
const floaterDirectory = resolve(repositoryRoot, 'node_modules', FLOATER.name);
const floaterManifest = JSON.parse(readFileSync(resolve(floaterDirectory, 'package.json'), 'utf8'));
const pinnedFloater = JSON.parse(readFileSync(resolve(repositoryRoot, 'package.json'), 'utf8')).devDependencies?.[
  FLOATER.name
];

if (floaterManifest.version !== FLOATER.version || pinnedFloater !== FLOATER.version) {
  throw new Error(
    `The Razor browser artifact bundles ${FLOATER.name} ${FLOATER.version} exactly, but the root package.json ` +
      `pins ${JSON.stringify(pinnedFloater)} and ${floaterManifest.version} is installed.`,
  );
}

const floaterNotice = readFileSync(resolve(floaterDirectory, 'LICENSE.md'), 'utf8').trim();
const floaterBanner =
  `/*!\n * vueforge-razor.js bundles ${FLOATER.name} ${FLOATER.version} (${floaterManifest.license}).\n *\n` +
  floaterNotice
    .split('\n')
    .map((line) => ` *${line ? ` ${line}` : ''}`)
    .join('\n') +
  '\n */';

const esbuildBinary = resolve(repositoryRoot, 'node_modules/.bin/esbuild');
const esbuildVersion = execFileSync(esbuildBinary, ['--version'], { encoding: 'utf8' }).trim();

execFileSync(
  esbuildBinary,
  [
    resolve(packageRoot, 'browser/input.ts'),
    '--bundle',
    '--format=esm',
    '--target=es2022',
    `--alias:@codemonster-ru/vueforge-shared-core=${resolve(repositoryRoot, 'packages/shared-core/src/index.ts')}`,
    // The theme package is neutral and published, but the controller is
    // bundled from source so a host never needs its dist: the accordion reads
    // the motion duration from it, exactly as the reference component does.
    `--alias:@codemonster-ru/vueforge-theme=${resolve(repositoryRoot, 'packages/theme/src/index.ts')}`,
    `--banner:js=${floaterBanner}`,
    `--outfile=${resolve(distDirectory, 'vueforge-razor.js')}`,
  ],
  { stdio: ['ignore', 'ignore', 'pipe'] },
);

const manifest = {
  $comment:
    'Generated by packages/razor/build-assets.mjs. Records where every packaged rule came from. ' +
    'Paths are repository relative on purpose: a distributable artifact must not carry the machine that built it.',
  styles: provenance,
  browser: {
    entry: 'packages/razor/browser/input.ts',
    bundles: ['packages/shared-core/src/index.ts', 'packages/theme/src/index.ts'],
    thirdParty: [{ name: FLOATER.name, version: FLOATER.version, license: floaterManifest.license }],
    tool: `esbuild ${esbuildVersion}`,
  },
  artifacts: Object.fromEntries(
    ['vueforge-razor.css', 'vueforge-razor.js'].map((name) => [
      name,
      createHash('sha256')
        .update(readFileSync(resolve(distDirectory, name)))
        .digest('hex'),
    ]),
  ),
};
writeFileSync(resolve(distDirectory, 'assets-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

process.stdout.write(
  `Built Razor assets in ${relative(repositoryRoot, distDirectory)}: ` +
    `${provenance.length} canonical stylesheet sources, 2 artifacts.\n`,
);
